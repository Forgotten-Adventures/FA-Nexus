const MODULE_ID = 'fa-nexus';
const ALLOWED_WRITE_OPTIONS = Object.freeze([
  'faNexusSceneGroupCommand',
  'faNexusSceneGroupDelete',
  'faNexusSceneGroupRollback',
  'faNexusPreviewDocument',
  'faNexusBuildingEditorDocumentWrite',
  'faNexusBuildingCurrentEdit',
  'faNexusBuildingNativeTransform',
  'faNexusBuildingNativeTransformRollback'
]);
const MANAGED_FILL_PRESENTATION_FIELDS = Object.freeze(new Set([
  'name',
  'elevation',
  'sort',
  'levels',
  'hidden',
  'locked'
]));
const MANAGED_FILL_PRESENTATION_PATHS = Object.freeze(new Set([
  `flags.${MODULE_ID}.name`,
  `flags.${MODULE_ID}.-=name`,
  `flags.${MODULE_ID}.layerHidden`,
  `flags.${MODULE_ID}.-=layerHidden`,
  `flags.${MODULE_ID}.placementLevelId`,
  `flags.${MODULE_ID}.-=placementLevelId`
]));

const MANAGED_SURFACE_REGION_PRESENTATION_FIELDS = Object.freeze(new Set([
  'name', 'color', 'visibility', 'hidden', 'locked', 'elevation', 'levels', 'behaviors'
]));

function normalizeIdentity(value) {
  return String(value || '').trim();
}

export function resolveBuildingGeneratedDocumentOwner({ scene, document } = {}) {
  const dependentUuid = normalizeIdentity(document?.uuid);
  const registry = scene?.getFlag?.(MODULE_ID, 'compositionRegistry') || null;
  const relationship = (Array.isArray(registry?.relationships) ? registry.relationships : []).find((candidate) => (
    normalizeIdentity(candidate?.dependentUuid) === dependentUuid
    && normalizeIdentity(candidate?.type) === 'generated-by'
    && normalizeIdentity(candidate?.generator) === 'building'
  )) || null;
  if (!relationship) return null;
  const ownerUuid = normalizeIdentity(relationship.ownerUuid);
  const ownerId = ownerUuid.split('.').pop() || null;
  const ownerDocument = ownerId
    ? (scene?.tiles?.get?.(ownerId) || scene?.getEmbeddedDocument?.('Tile', ownerId) || null)
    : null;
  return { relationship, ownerUuid, ownerDocument, dependentUuid };
}

export function formatBuildingGeneratedDocumentOwnershipExplanation(ownership) {
  const ownerId = normalizeIdentity(ownership?.ownerDocument?.id)
    || normalizeIdentity(ownership?.ownerUuid).split('.').pop()
    || 'unavailable';
  return `This document is generated by Building Tile ${ownerId}. Edit the owning Building instead.`;
}

export function isBuildingGeneratedDocumentWriteAllowed(options = {}) {
  return ALLOWED_WRITE_OPTIONS.some((key) => options?.[key] === true);
}

export function isBuildingGeneratedDocumentLiveStateUpdate(document, changes = {}) {
  const changedKeys = Object.keys(changes || {}).filter((key) => key !== '_id');
  return normalizeIdentity(document?.documentName || document?.constructor?.documentName) === 'Wall'
    && Number(document?.door || 0) > 0
    && changedKeys.length === 1
    && changedKeys[0] === 'ds';
}

export function isBuildingManagedFillDocument(document) {
  return isBuildingManagedArtworkDocument(document, 'fill', 'buildingFill');
}

export function isBuildingManagedSillsDocument(document) {
  return isBuildingManagedArtworkDocument(document, 'sill', 'buildingSills');
}

function isBuildingManagedArtworkDocument(document, role, flagKey) {
  if (normalizeIdentity(document?.documentName || document?.constructor?.documentName) !== 'Tile') return false;
  const faNexus = document?.flags?.[MODULE_ID]
    || document?._source?.flags?.[MODULE_ID]
    || {};
  const generated = faNexus?.buildingGenerated || null;
  const fill = faNexus?.[flagKey] || null;
  const rootTileId = normalizeIdentity(generated?.rootTileId);
  return Number(generated?.version) === 1
    && generated?.role === role
    && generated?.semanticId === null
    && !!rootTileId
    && Number(fill?.version) === 1
    && normalizeIdentity(fill?.wallTileId) === rootTileId;
}

export function isBuildingManagedSurfaceRegionDocument(document) {
  if (normalizeIdentity(document?.documentName || document?.constructor?.documentName) !== 'Region') return false;
  const generated = (document?._source?.flags || document?.flags)?.[MODULE_ID]?.buildingGenerated;
  if (Number(generated?.version) !== 1 || generated?.role !== 'surface-region'
    || generated?.semanticId !== null || generated?.fragmentOrdinal !== 0
    || !normalizeIdentity(generated?.rootTileId) || !normalizeIdentity(generated?.buildingId)
    || !normalizeIdentity(generated?.generationId)) return false;
  const scene = document?.parent || globalThis.canvas?.scene || null;
  const ownership = resolveBuildingGeneratedDocumentOwner({ scene, document });
  const root = ownership?.ownerDocument;
  const building = root?.getFlag?.(MODULE_ID, 'building')
    || (root?._source?.flags || root?.flags)?.[MODULE_ID]?.building;
  return !!root && normalizeIdentity(root.id || root._id) === generated.rootTileId
    && normalizeIdentity(root.uuid) === ownership.ownerUuid
    && [4, 5].includes(Number(building?.schemaVersion))
    && building?.buildingId === generated.buildingId
    && building?.runtime?.generationId === generated.generationId;
}

export function isBuildingManagedSurfaceRegionPresentationUpdate(document, changes = {}) {
  return isBuildingManagedSurfaceRegionDocument(document)
    && matchesDocumentPresentationUpdate(document, changes, MANAGED_SURFACE_REGION_PRESENTATION_FIELDS);
}

export function isBuildingManagedFillPresentationUpdate(document, changes = {}) {
  return isBuildingManagedFillDocument(document)
    && matchesDocumentPresentationUpdate(document, changes, MANAGED_FILL_PRESENTATION_FIELDS, MANAGED_FILL_PRESENTATION_PATHS);
}

export function isBuildingManagedSillsPresentationUpdate(document, changes = {}) {
  return isBuildingManagedSillsDocument(document)
    && matchesDocumentPresentationUpdate(document, changes, MANAGED_FILL_PRESENTATION_FIELDS, MANAGED_FILL_PRESENTATION_PATHS);
}

function matchesDocumentPresentationUpdate(document, changes, fields, paths = null) {
  const changedKeys = Object.keys(changes || {}).filter((key) => key !== '_id');
  if (!changedKeys.length) return false;
  const source = document?._source || document || {};
  const matchesEffectivePresentationUpdate = (current, incoming, path) => {
    const topLevel = path.split('.')[0];
    if (fields.has(topLevel) || paths?.has(path)) return true;
    if (Array.isArray(incoming)) {
      return Array.isArray(current)
        && incoming.length === current.length
        && incoming.every((value, index) => matchesEffectivePresentationUpdate(current[index], value, `${path}.${index}`));
    }
    if (incoming && typeof incoming === 'object') {
      return current && typeof current === 'object'
        && Object.entries(incoming).every(([key, value]) => (
          matchesEffectivePresentationUpdate(current[key], value, `${path}.${key}`)
        ));
    }
    return Object.is(current, incoming);
  };
  return changedKeys.every((key) => {
    if (key.includes('.')) {
      const current = key.split('.').reduce((owner, part) => owner?.[part], source);
      return matchesEffectivePresentationUpdate(current, changes[key], key);
    }
    return matchesEffectivePresentationUpdate(source[key], changes[key], key);
  });
}

export function normalizeBuildingManagedFillTileConfigPresentationUpdate(document, changes = {}) {
  if (!isBuildingManagedFillDocument(document) || !changes || typeof changes !== 'object') return changes;
  const keys = Object.keys(changes).filter((key) => key !== '_id');
  const hasPresentationIntent = keys.some((key) => MANAGED_FILL_PRESENTATION_FIELDS.has(key.split('.')[0]));
  const isBroadTileConfigPayload = ['x', 'y', 'width', 'height', 'rotation', 'texture', 'alpha']
    .every((key) => Object.prototype.hasOwnProperty.call(changes, key));
  const currentAlpha = Number(document?._source?.alpha ?? document?.alpha);
  const submittedAlpha = Number(changes.alpha);
  // Foundry v14 Tile Config serializes its untouched alpha range at one-decimal precision.
  // Preserve the exact authored Fill opacity when a broad form submit only carries that rounding.
  if (hasPresentationIntent && isBroadTileConfigPayload
    && Number.isFinite(currentAlpha) && Number.isFinite(submittedAlpha)
    && submittedAlpha !== currentAlpha
    && submittedAlpha === Math.round(currentAlpha * 10) / 10) {
    changes.alpha = currentAlpha;
  }
  return changes;
}

export function createBuildingGeneratedDocumentEditorOptions(document, {
  source = 'building-generated-document-edit-routing'
} = {}) {
  const faNexus = document?.flags?.[MODULE_ID]
    || document?._source?.flags?.[MODULE_ID]
    || {};
  const semanticSegmentId = normalizeIdentity(faNexus?.buildingWall?.semanticSegmentId);
  const portalId = normalizeIdentity(faNexus?.buildingWall?.portalId)
    || normalizeIdentity(faNexus?.buildingDoor?.gapId)
    || normalizeIdentity(faNexus?.buildingWindow?.gapId)
    || normalizeIdentity(faNexus?.buildingSeamlessSecretDoor?.gapId);
  return {
    source,
    ...(portalId ? {
      portalFocusId: portalId,
      portalCommitOnSave: true
    } : {}),
    ...(semanticSegmentId ? {
      wallBehaviorFocusSegmentId: semanticSegmentId,
      wallBehaviorCommitOnSave: true
    } : {})
  };
}

async function routeConfigToBuildingEditor(application) {
  if (application?.faNexusBuildingGeneratedDocumentRouted) return;
  const document = application?.document || application?.object || null;
  const scene = document?.parent || globalThis.canvas?.scene || null;
  const ownership = resolveBuildingGeneratedDocumentOwner({ scene, document });
  if (!ownership) return;
  application.faNexusBuildingGeneratedDocumentRouted = true;
  const explanation = formatBuildingGeneratedDocumentOwnershipExplanation(ownership);
  try {
    await application.close?.({ animate: false });
    if (!ownership.ownerDocument) throw new Error(`${explanation} The owning Tile is unavailable.`);
    globalThis.ui?.notifications?.info?.(explanation);
    const { openFaNexusTileEditor } = await import('../canvas/tile-hud-edit.js');
    await openFaNexusTileEditor(
      ownership.ownerDocument,
      createBuildingGeneratedDocumentEditorOptions(document)
    );
  } catch (error) {
    Logger.error('BuildingGeneratedDocumentRuntime.editRouting.failed', {
      dependentUuid: normalizeIdentity(document?.uuid),
      ownerUuid: ownership.ownerUuid,
      error: String(error?.message || error)
    });
    globalThis.ui?.notifications?.error?.(`${explanation} ${error?.message || error}`);
  }
}

function blockDirectGeneratedDocumentUpdate(document, changes, options = {}, userId = null) {
  if (isBuildingGeneratedDocumentWriteAllowed(options)) return true;
  if (isBuildingGeneratedDocumentLiveStateUpdate(document, changes)) return true;
  if (userId && userId !== globalThis.game?.user?.id) return true;
  const scene = document?.parent || globalThis.canvas?.scene || null;
  const ownership = resolveBuildingGeneratedDocumentOwner({ scene, document });
  if (!ownership) return true;
  normalizeBuildingManagedFillTileConfigPresentationUpdate(document, changes);
  if (isBuildingManagedFillPresentationUpdate(document, changes)
    || isBuildingManagedSillsPresentationUpdate(document, changes)
    || isBuildingManagedSurfaceRegionPresentationUpdate(document, changes)) return true;
  const explanation = formatBuildingGeneratedDocumentOwnershipExplanation(ownership);
  Logger.warn('BuildingGeneratedDocumentRuntime.directUpdate.blocked', {
    dependentUuid: normalizeIdentity(document?.uuid),
    ownerUuid: ownership.ownerUuid,
    changes: Object.keys(changes || {})
  });
  notifyGeneratedDocumentRefusal(explanation);
  return false;
}

function blockDirectGeneratedDocumentDeletion(document, options = {}, userId = null) {
  if (isBuildingGeneratedDocumentWriteAllowed(options)) return true;
  if (userId && userId !== globalThis.game?.user?.id) return true;
  const scene = document?.parent || globalThis.canvas?.scene || null;
  const ownership = resolveBuildingGeneratedDocumentOwner({ scene, document });
  if (!ownership || !ownership.ownerDocument) return true;
  const explanation = formatBuildingGeneratedDocumentOwnershipExplanation(ownership);
  Logger.warn('BuildingGeneratedDocumentRuntime.directDelete.blocked', {
    dependentUuid: normalizeIdentity(document?.uuid),
    ownerUuid: ownership.ownerUuid
  });
  notifyGeneratedDocumentRefusal(explanation);
  return false;
}

/**
 * Foundry's native paste clones every flag. A pasted Wall or Region would keep naming
 * its source Building as generator; the Building's exact-manifest check then finds an
 * unlisted generated document and refuses every transform. A native copy is an
 * ordinary independent document, so it leaves all Building identity behind.
 */
function releasePastedGeneratedDocuments(objects, data, { cut = false } = {}) {
  if (!Array.isArray(objects) || !Array.isArray(data)) return;
  for (let index = 0; index < data.length; index += 1) {
    const flags = data[index]?.flags?.[MODULE_ID];
    if (!flags?.buildingGenerated) continue;
    // Cutting within one Scene updates the generated document itself, which the
    // direct-update guard already refuses with its owner explanation.
    if (cut && objects[index]?.document?.parent === globalThis.canvas?.scene) continue;
    for (const key of Object.keys(flags)) {
      if (key.startsWith('building')) delete flags[key];
    }
    if (!Object.keys(flags).length) delete data[index].flags[MODULE_ID];
  }
}

function blockPartialBuildingLevelDeletion(level, options = {}, userId = null) {
  if (isBuildingGeneratedDocumentWriteAllowed(options)) return true;
  if (userId && userId !== globalThis.game?.user?.id) return true;
  const scene = level.parent;
  // Foundry's server-side Level cascade bypasses preDeleteWall/Tile/Region.
  // Match its deletion scope: automatic and multi-Level members survive.
  const removedByLevel = (document) => document?.levels?.size === 1 && document.levels.has(level.id);
  const affected = [];
  for (const document of [...scene.tiles, ...scene.walls, ...scene.regions]) {
    if (!removedByLevel(document)) continue;
    const ownership = resolveBuildingGeneratedDocumentOwner({ scene, document });
    if (ownership?.ownerDocument && !removedByLevel(ownership.ownerDocument)) affected.push(ownership);
  }
  if (!affected.length) return true;
  const ownerUuids = [...new Set(affected.map(entry => entry.ownerUuid))];
  Logger.warn('BuildingGeneratedDocumentRuntime.levelDelete.blocked', {
    levelId: level.id, ownerUuids, dependentUuids: affected.map(entry => entry.dependentUuid)
  });
  globalThis.ui?.notifications?.warn?.(`Cannot delete Level "${level.name}": it would delete generated parts of ${ownerUuids.length} Building(s) while leaving their Roots. Delete the owning Buildings first.`);
  return false;
}

if (globalThis.Hooks?.on) {
  Hooks.on('preDeleteLevel', blockPartialBuildingLevelDeletion);
  Hooks.on('preUpdateScene', (scene, changes, options) => {
    try {
      if (!projectCompositionSceneReposition(scene, changes, options)) projectBuildingV2PortalScalesForSceneGrid(scene, changes);
    } catch (error) {
      const message = String(error?.message || error);
      Logger.error('CompositionSceneProjection.failed', {sceneId: scene.id, error: message});
      globalThis.ui?.notifications?.error?.(message);
      return false;
    }
  });
  Hooks.on('renderTileConfig', (application) => {
    const document = application?.document || application?.object || null;
    if (isBuildingManagedFillDocument(document) || isBuildingManagedSillsDocument(document)) return;
    void routeConfigToBuildingEditor(application);
  });
  for (const hook of ['renderWallConfig', 'renderRegionConfig', 'renderRegionConfigV2']) {
    Hooks.on(hook, (application) => {
      const document = application?.document || application?.object || null;
      if (isBuildingManagedSurfaceRegionDocument(document)) return;
      void routeConfigToBuildingEditor(application);
    });
  }
  for (const documentName of ['Wall', 'Region']) {
    Hooks.on(`paste${documentName}`, releasePastedGeneratedDocuments);
  }
  for (const documentName of ['Tile', 'Wall', 'Region']) {
    Hooks.on(`preUpdate${documentName}`, blockDirectGeneratedDocumentUpdate);
    Hooks.on(`preDelete${documentName}`, blockDirectGeneratedDocumentDeletion);
  }
}
