import { NexusLogger as Logger } from '../core/nexus-logger.js';
import { notifyGeneratedDocumentRefusal } from '../core/generated-document-refusal-notice.js';

const MODULE_ID = 'fa-nexus';
const ALLOWED_WRITE_OPTIONS = Object.freeze([
  'faNexusSceneGroupCommand',
  'faNexusSceneGroupDelete',
  'faNexusPathGeneratedWallOwnership',
  'faNexusPathEditorWallWrite',
  'faNexusPathNativeTransform',
  'faNexusPathNativeTransformRollback'
]);

function normalizeIdentity(value) {
  return String(value || '').trim();
}

export function resolvePathGeneratedWallOwner({ scene, wall } = {}) {
  const wallUuid = normalizeIdentity(wall?.uuid);
  const registry = scene?.getFlag?.(MODULE_ID, 'compositionRegistry') || null;
  const relationship = (Array.isArray(registry?.relationships) ? registry.relationships : []).find((candidate) => (
    normalizeIdentity(candidate?.dependentUuid) === wallUuid
    && normalizeIdentity(candidate?.type) === 'generated-by'
    && normalizeIdentity(candidate?.generator) === 'path-v2'
  )) || null;
  if (!relationship) return null;
  const ownerUuid = normalizeIdentity(relationship.ownerUuid);
  const ownerId = ownerUuid.split('.').pop() || null;
  const ownerDocument = ownerId
    ? (scene?.tiles?.get?.(ownerId) || scene?.getEmbeddedDocument?.('Tile', ownerId) || null)
    : null;
  return {
    relationship,
    ownerUuid,
    ownerDocument,
    dependentUuid: wallUuid
  };
}

export function formatPathGeneratedWallOwnershipExplanation(ownership) {
  const ownerId = normalizeIdentity(ownership?.ownerDocument?.id)
    || normalizeIdentity(ownership?.ownerUuid).split('.').pop()
    || 'unavailable';
  return `This Wall is generated by Path Tile ${ownerId}. Edit the owning Path instead.`;
}

export function isPathGeneratedWallWriteAllowed(options = {}) {
  return ALLOWED_WRITE_OPTIONS.some((key) => options?.[key] === true);
}

async function routeWallConfigToPathEditor(application) {
  if (application?.faNexusPathGeneratedWallRouted) return;
  const wall = application?.document || application?.object || null;
  const scene = wall?.parent || globalThis.canvas?.scene || null;
  const ownership = resolvePathGeneratedWallOwner({ scene, wall });
  if (!ownership) return;
  application.faNexusPathGeneratedWallRouted = true;
  const explanation = formatPathGeneratedWallOwnershipExplanation(ownership);
  try {
    await application.close?.({ animate: false });
    if (!ownership.ownerDocument) throw new Error(`${explanation} The owning Tile is unavailable.`);
    globalThis.ui?.notifications?.info?.(explanation);
    const { openFaNexusTileEditor } = await import('../canvas/tile-hud-edit.js');
    await openFaNexusTileEditor(ownership.ownerDocument, {
      source: 'path-generated-wall-edit-routing'
    });
  } catch (error) {
    Logger.error('PathGeneratedWallRuntime.editRouting.failed', {
      wallUuid: normalizeIdentity(wall?.uuid),
      ownerUuid: ownership.ownerUuid,
      error: String(error?.message || error)
    });
    globalThis.ui?.notifications?.error?.(`${explanation} ${error?.message || error}`);
  }
}

function blockDirectGeneratedWallUpdate(wall, _changes, options = {}, userId = null) {
  if (isPathGeneratedWallWriteAllowed(options)) return true;
  if (userId && userId !== globalThis.game?.user?.id) return true;
  const scene = wall?.parent || globalThis.canvas?.scene || null;
  const ownership = resolvePathGeneratedWallOwner({ scene, wall });
  if (!ownership) return true;
  const explanation = formatPathGeneratedWallOwnershipExplanation(ownership);
  Logger.warn('PathGeneratedWallRuntime.directUpdate.blocked', {
    wallUuid: normalizeIdentity(wall?.uuid),
    ownerUuid: ownership.ownerUuid,
    changes: Object.keys(_changes || {})
  });
  notifyGeneratedDocumentRefusal(explanation);
  return false;
}

function blockDirectGeneratedWallDeletion(wall, options = {}, userId = null) {
  if (isPathGeneratedWallWriteAllowed(options)) return true;
  if (userId && userId !== globalThis.game?.user?.id) return true;
  const scene = wall?.parent || globalThis.canvas?.scene || null;
  const ownership = resolvePathGeneratedWallOwner({ scene, wall });
  if (!ownership || !ownership.ownerDocument) return true;
  const explanation = formatPathGeneratedWallOwnershipExplanation(ownership);
  Logger.warn('PathGeneratedWallRuntime.directDelete.blocked', {
    wallUuid: normalizeIdentity(wall?.uuid),
    ownerUuid: ownership.ownerUuid
  });
  notifyGeneratedDocumentRefusal(explanation);
  return false;
}

/**
 * Native Undo of a Path edit restores the Tile alone. When that edit regenerated the Path's
 * Foundry Walls, the restored record lists Walls that no longer exist while the current ones
 * stay, so artwork and Walls disagree. That one Undo is refused with its reason; Undo entries
 * recorded by Nexus commands restore the Walls themselves and carry their own options.
 */
function blockUndoToMissingGeneratedWalls(tile, changes, options = {}, userId = null) {
  if (options?.isUndo !== true) return true;
  if (userId && userId !== globalThis.game?.user?.id) return true;
  if (Object.keys(options).some((key) => key.startsWith('faNexus'))) return true;
  const restored = changes?.flags?.[MODULE_ID];
  const records = [restored?.pathV2, ...(Array.isArray(restored?.pathsV2?.paths) ? restored.pathsV2.paths : [])];
  const walls = (tile?.parent || globalThis.canvas?.scene)?.walls;
  const missing = records.flatMap((record) => (Array.isArray(record?.foundryWalls?.wallIds) ? record.foundryWalls.wallIds : []))
    .filter((wallId) => !walls?.get?.(wallId));
  if (!missing.length) return true;
  Logger.warn('PathGeneratedWallRuntime.undo.blocked', {
    tileUuid: normalizeIdentity(tile?.uuid),
    missingWallIds: missing
  });
  globalThis.ui?.notifications?.warn?.(
    'This Path edit regenerated its Foundry Walls, so Undo cannot take the Tile back without them. Edit the Path again instead.'
  );
  return false;
}

/**
 * Foundry's native paste clones every flag. A pasted Wall would keep naming its source Path as
 * generator: the Path editor matches a Path's Walls by that flag and would remove the copy on
 * the next edit. The copy is an ordinary Wall. A cut within the Scene is a move of the
 * generated Wall itself, which the direct-update guard already refuses.
 */
function releasePastedPathWalls(objects, data, { cut = false } = {}) {
  if (!Array.isArray(objects) || !Array.isArray(data)) return;
  for (let index = 0; index < data.length; index += 1) {
    const flags = data[index]?.flags?.[MODULE_ID];
    if (!flags?.pathWall) continue;
    if (cut && objects[index]?.document?.parent === globalThis.canvas?.scene) continue;
    delete flags.pathWall;
    if (!Object.keys(flags).length) delete data[index].flags[MODULE_ID];
  }
}

if (globalThis.Hooks?.on) {
  Hooks.on('pasteWall', releasePastedPathWalls);
  Hooks.on('renderWallConfig', (application) => {
    void routeWallConfigToPathEditor(application);
  });
  Hooks.on('preUpdateWall', blockDirectGeneratedWallUpdate);
  Hooks.on('preDeleteWall', blockDirectGeneratedWallDeletion);
  Hooks.on('preUpdateTile', blockUndoToMissingGeneratedWalls);
}
